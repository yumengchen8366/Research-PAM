%% 2. 运行换算，核对预测
% double：转换数据类型，这一步不改变这些原始码的数值。
% / 65535：映射到 0～1。
% * 2 - 1：映射到 -1～+1。
% * inputRange_V：映射到 -4～+4 V。
volts = (double(raw) / 65535 * 2 - 1) * inputRange_V;
result = table(raw, volts, 'VariableNames', {'RawCode', 'Voltage_V'});
disp(result);


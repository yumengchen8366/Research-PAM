function handle = AlazarGetBoardBySystemHandle(boardHandle, boardId)
    handle = calllib('ATSApi', ...
                     'AlazarGetBoardBySystemHandle', ...
                     boardHandle, ...
                     boardId);
    if isNull(handle)
        throw(MException('AlazarGetBoardBySystemHandle:error', ...
                         'NULL board'));
    end
end

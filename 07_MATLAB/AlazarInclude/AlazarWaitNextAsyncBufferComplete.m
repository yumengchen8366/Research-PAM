function AlazarWaitNextAsyncBufferComplete(boardHandle, ...
                                           pBuffer, ...
                                           bytesToCopy, ...
                                           timeout_ms)
    retCode = calllib('ATSApi', ...
                      'AlazarWaitNextAsyncBufferComplete', ...
                      boardHandle, ...
                      pBuffer, ...
                      bytesToCopy, ...
                      timeout_ms);
    if retCode ~= 512
        throw(MException('AlazarWaitNextAsyncBufferComplete:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

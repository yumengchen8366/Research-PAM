function AlazarDSPGetBuffer(boardHandle, buffer, timeout_ms)
    retCode = calllib('ATSApi', ...
                      'AlazarDSPGetBuffer', ...
                      boardHandle, ...
                      buffer, ...
                      timeout_ms);
    if retCode ~= 512
        throw(MException('AlazarDSPGetBuffer:error', '%s', errorToText(retCode)));
    end
end

function AlazarFFTSetGainAndOffset(dspHandle, ...
                                    gain, ...
                                    offset)
    retCode = calllib('ATSApi', ...
                      'AlazarFFTSetGainAndOffset', ...
                      dspHandle, ...
                      gain, ...
                      offset);
    if retCode ~= 512
        throw(MException('AlazarFFTSetGainAndOffset:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

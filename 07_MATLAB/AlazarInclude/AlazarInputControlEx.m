function AlazarInputControlEx(boardHandle, ...
                              channelId, ...
                              couplingId, ...
                              rangeId, ...
                              impedanceId)
    retCode = calllib('ATSApi', ...
                      'AlazarInputControlEx', ...
                      boardHandle, ...
                      channelId, ...
                      couplingId, ...
                      rangeId, ...
                      impedanceId);
    if retCode ~= 512
        throw(MException('AlazarInputControlEx:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

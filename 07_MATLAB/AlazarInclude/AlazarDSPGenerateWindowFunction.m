function window = AlazarDSPGenerateWindowFunction(windowType, ...
                                         windowLength_samples, ...
                                         paddingLength_samples)
    pWindow = libpointer('singlePtr', ...
        zeros(windowLength_samples + paddingLength_samples, 1));
    retCode = calllib('ATSApi', ...
                      'AlazarDSPGenerateWindowFunction', ...
                      windowType, ...
                      pWindow, ...
                      windowLength_samples, ...
                      paddingLength_samples);
    if retCode ~= 512
        throw(MException('AlazarDSPGenerateWindowFunction:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
    window = pWindow.Value;
end

function AlazarSetExternalTrigger(boardHandle, couplingId, rangeId)
    retCode = calllib('ATSApi', ...
                      'AlazarSetExternalTrigger', ...
                      boardHandle, ...
                      couplingId, ...
                      rangeId);
    if retCode ~= 512
        throw(MException('AlazarSetExternalTrigger:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

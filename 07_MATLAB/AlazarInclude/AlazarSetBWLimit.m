function AlazarSetBWLimit(boardHandle, channelId, flag)
    retCode = calllib('ATSApi', ...
                      'AlazarSetBWLimit', ...
                      boardHandle, ...
                      channelId, ...
                      flag);
    if retCode ~= 512
        throw(MException('AlazarSetBWLimit:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

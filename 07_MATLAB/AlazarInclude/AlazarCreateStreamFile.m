function AlazarCreateStreamFile(boardHandle, ...
                                filePath)
    retCode = calllib('ATSApi', ...
                      'AlazarCreateStreamFile', ...
                      boardHandle, ...
                      filePath);
    if retCode ~= 512
        throw(MException('AlazarCreateStreamFile:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

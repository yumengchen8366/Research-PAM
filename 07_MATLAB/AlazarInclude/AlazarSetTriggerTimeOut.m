function AlazarSetTriggerTimeOut(boardHandle, timeoutTicks)
    retCode = calllib('ATSApi', ...
                      'AlazarSetTriggerTimeOut', ...
                      boardHandle, ...
                      timeoutTicks);
    if retCode ~= 512
        throw(MException('AlazarSetTriggerTimeOut:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

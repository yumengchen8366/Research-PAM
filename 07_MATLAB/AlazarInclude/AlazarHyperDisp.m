function error = AlazarHyperDisp(boardHandle, ...
                                 pBuffer, ...
                                 bufferSize, ...
                                 pViewBuffer, ...
                                 viewBufferSize, ...
                                 numOfPixels, ...
                                 option, ...
                                 channelSelect, ...
                                 record, ...
                                 transferOffset)
    pError = libpointer('uint32Ptr', 0);
    retCode = calllib('ATSApi', ...
                      'AlazarHyperDisp', ...
                      boardHandle, ...
                      pBuffer, ...
                      bufferSize, ...
                      pViewBuffer, ...
                      viewBufferSize, ...
                      numOfPixels, ...
                      option, ...
                      channelSelect, ...
                      record, ...
                      transferOffset, ...
                      pError);
    if retCode ~= 512
        throw(MException('AlazarHyperDisp:error', '%s', errorToText(retCode)));
    end
    error = pError.Value;
end

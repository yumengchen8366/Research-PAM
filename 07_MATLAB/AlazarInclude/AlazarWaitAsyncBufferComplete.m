function AlazarWaitAsyncBufferComplete(boardHandle, pBuffer, timeout_ms)
    retCode = calllib('ATSApi', ...
                      'AlazarWaitAsyncBufferComplete', ...
                      boardHandle, ...
                      pBuffer, ...
                      timeout_ms);
    if retCode ~= 512
        throw(MException('AlazarWaitAsyncBufferComplete:error', ...
                         '%s', errorToText(retCode)));
    end
end

function AlazarCoprocessorRegisterWrite(boardHandle, offset, value)
    retCode = calllib('ATSApi', ...
                      'AlazarCoprocessorRegisterWrite', ...
                      boardHandle, ...
                      offset, ...
                      value);
    if retCode ~= 512
        throw(MException('AlazarCoprocessorRegisterWrite:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

function AlazarSetCaptureClock(boardHandle, ...
                               sourceId, ...
                               sampleRateId, ...
                               edgeId, ...
                               decimation)
    retCode = calllib('ATSApi', ...
                      'AlazarSetCaptureClock', ...
                      boardHandle, ...
                      sourceId, ...
                      sampleRateId, ...
                      edgeId, ...
                      decimation);
    if retCode ~= 512
        throw(MException('AlazarSetCaptureClock:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

function AlazarFFTSetWindowFunction(dspHandle, ...
                                    realWindowArray, ...
                                    imagWindowArray)
    pRealWindowArray = libpointer('singlePtr', realWindowArray);
    pImagWindowArray = libpointer('singlePtr', imagWindowArray);
    samplesPerRecord = numel(realWindowArray);
    if samplesPerRecord ~= numel(imagWindowArray)
        throw(MException('AlazarFFTSetWindowFunction:error', ...
            'Arrays must have same size'));
    end
    retCode = calllib('ATSApi', ...
                      'AlazarFFTSetWindowFunction', ...
                      dspHandle, ...
                      samplesPerRecord, ...
                      pRealWindowArray, ...
                      pImagWindowArray);
    if retCode ~= 512
        throw(MException('AlazarFFTSetWindowFunction:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

function AlazarSetExternalClockLevel(boardHandle, level_percent)
    retCode = calllib('ATSApi', ...
                      'AlazarSetExternalClockLevel', ...
                      boardHandle, ...
                      level_percent);
    if retCode ~= 512
        throw(MException('AlazarSetExternalClockLevel:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

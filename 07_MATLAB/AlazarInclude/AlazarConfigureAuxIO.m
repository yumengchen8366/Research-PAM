function AlazarConfigureAuxIO(boardHandle, mode, parameter)
    retCode = calllib('ATSApi', ...
                      'AlazarConfigureAuxIO', ...
                      boardHandle, ...
                      mode, ...
                      parameter);
    if retCode ~= 512
        throw(MException('AlazarConfigureAuxIO:error', '%s', errorToText(retCode)));
    end
end

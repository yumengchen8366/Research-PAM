function [maxRecordsPerCapture] = ...
         AlazarGetMaxRecordsCapable(handle, samplesPerRecord)
    pMaxRecordsPerCapture = libpointer('uint32Ptr', 0);
    retCode = calllib('ATSApi', ...
                      'AlazarGetMaxRecordsCapable', ...
                      handle, ...
                      samplesPerRecord, ...
                      pMaxRecordsPerCapture);
    if retCode ~= 512
        throw(MException('AlazarGetMaxRecordsCapable:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
    maxRecordsPerCapture = pMaxRecordsPerCapture.Value;
end

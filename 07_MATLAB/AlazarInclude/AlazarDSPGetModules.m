function modules = AlazarDSPGetModules(boardHandle)
    pNumModules = libpointer('uint32Ptr', 0);
    retCode = calllib('ATSApi', ...
                      'AlazarDSPGetModules', ...
                      boardHandle, ...
                      0, ...
                      libpointer, ...
                      pNumModules);
    if retCode ~= 512
        throw(MException('AlazarDSPGetModules:error', '%s', errorToText(retCode)));
    end

    numModules = pNumModules.Value;
    if numModules < 1
        return
    end

    modules = libpointer('dsp_module_descriptorPtr', ...
        repmat(struct(), 1, numModules));

    retCode = calllib('ATSApi', ...
                      'AlazarDSPGetModules', ...
                      boardHandle, ...
                      numModules, ...
                      modules, ...
                      0);
    if retCode ~= 512
        throw(MException('AlazarDSPGetModules:error', '%s', errorToText(retCode)));
    end
end

function value = AlazarGetParameterUL(boardHandle, ...
                                      channel, ...
                                      parameter)
    pValue = libpointer('uint32Ptr', 0);
    retCode = calllib('ATSApi', ...
                      'AlazarGetParameterUL', ...
                      boardHandle, ...
                      channel, ...
                      parameter, ...
                      pValue);
    if retCode ~= 512
        throw(MException('AlazarGetParameterUL:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
    value = pValue.Value;
end

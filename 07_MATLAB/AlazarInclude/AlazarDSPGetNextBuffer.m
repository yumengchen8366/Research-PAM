function AlazarDSPGetNextBuffer(boardHandle, ...
                                pBuffer, ...
                                bytesToCopy, ...
                                timeout_ms)
    retCode = calllib('ATSApi', ...
                      'AlazarDSPGetNextBuffer', ...
                      boardHandle, ...
                      pBuffer, ...
                      bytesToCopy, ...
                      timeout_ms);
    if retCode ~= 512
        throw(MException('AlazarDSPGetNextBuffer:error', '%s', errorToText(retCode)));
    end
end

function maxTriggerRepeatRate = AlazarFFTGetMaxTriggerRepeatRate(dspHandle, ...
                                                                 fft_size)
    pMaxTriggerRepeatRate = libpointer('doublePtr', 0);
    retCode = calllib('ATSApi', ...
                      'AlazarFFTGetMaxTriggerRepeatRate', ...
                      dspHandle, ...
                      fft_size, ...
                      pMaxTriggerRepeatRate);
    if retCode ~= 512
        throw(MException('AlazarFFTGetMaxTriggerRepeatRate:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
    maxTriggerRepeatRate = pMaxTriggerRepeatRate.Value;
end

function AlazarFFTBackgroundSubtractionSetRecordS16(dspHandle, record)
    pRecord = libpointer('int16Ptr', record);
    retCode = calllib('ATSApi', ...
                      'AlazarFFTBackgroundSubtractionSetRecordS16', ...
                      dspHandle, ...
                      pRecord, ...
                      numel(record));
    if retCode ~= 512
        throw(MException('AlazarFFTBackgroundSubtractionSetRecordS16:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

function AlazarSetParameter(boardHandle, channelId, parameterId, value)
    retCode = calllib('ATSApi', ...
                      'AlazarSetParameterUL', ...
                      boardHandle, ...
                      channelId, ...
                      parameterId, ...
                      value);
    if retCode ~= 512
        throw(MException('AlazarSetParameter:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

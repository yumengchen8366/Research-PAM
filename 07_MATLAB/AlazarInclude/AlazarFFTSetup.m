function bytesPerOutputRecord = AlazarFFTSetup(dspHandle, ...
                                               inputChannelMask, ...
                                               recordLength_samples, ...
                                               fftLength_samples, ...
                                               outputFormat, ...
                                               footer)
    pBytesPerOutputRecord = libpointer('uint32Ptr', 0);
    retCode = calllib('ATSApi', ...
                      'AlazarFFTSetup', ...
                      dspHandle, ...
                      inputChannelMask, ...
                      recordLength_samples, ...
                      fftLength_samples, ...
                      outputFormat, ...
                      footer, ...
                      0, ...
                      pBytesPerOutputRecord);
    if retCode ~= 512
        throw(MException('AlazarFFTSetup:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
    bytesPerOutputRecord = pBytesPerOutputRecord.Value;
end

function AlazarCoprocessorDownload(boardHandle, fileName, options)
    retCode = calllib('ATSApi', ...
                      'AlazarCoprocessorDownload', ...
                      boardHandle, ...
                      fileName, ...
                      options);
    if retCode ~= 512
        throw(MException('AlazarCoprocessorDownload:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

function value = AlazarCoprocessorRegisterRead(boardHandle, ...
                                               offset)
    pValue = libpointer('uint32Ptr', 0);
    retCode = calllib('ATSApi', ...
                      'AlazarCoprocessorRegisterRead', ...
                      boardHandle, ...
                      offset, ...
                      pValue);
    if retCode ~= 512
        throw(MException('AlazarCoprocessorRegisterRead:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
    value = pValue.Value;
end

function AlazarSetRecordSize(boardHandle, ...
                             preTriggerSamples, ...
                             postTriggerSamples)
    retCode = calllib('ATSApi', ...
                      'AlazarSetRecordSize', ...
                      boardHandle, ...
                      preTriggerSamples, ...
                      postTriggerSamples);
    if retCode ~= 512
        throw(MException('AlazarSetRecordSize:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

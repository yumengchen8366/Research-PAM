function AlazarSetRecordCount(boardHandle, recordsPerCapture)
    retCode = calllib('ATSApi', ...
                      'AlazarSetRecordCount', ...
                      boardHandle, ...
                      recordsPerCapture);
    if retCode ~= 512
        throw(MException('AlazarSetRecordCount:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

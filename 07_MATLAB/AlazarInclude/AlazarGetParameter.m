function value = AlazarGetParameter(boardHandle, channel, parameter)
    pValue = libpointer('longPtr', 0);
    retCode = calllib('ATSApi', ...
                      'AlazarGetParameter', ...
                      boardHandle, ...
                      channel, ...
                      parameter, ...
                      pValue);
    if retCode ~= 512
        throw(MException('AlazarGetParameter:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
    value = pValue.Value;
end

function AlazarConfigureRecordAverage(boardHandle, ...
                                      mode, ...
                                      samplesPerRecord, ...
                                      recordsPerAverage, ...
                                      options)
    retCode = calllib('ATSApi', ...
                      'AlazarConfigureRecordAverage', ...
                      boardHandle, ...
                      mode, ...
                      samplesPerRecord, ...
                      recordsPerAverage, ...
                      options);
    if retCode ~= 512
        throw(MException('AlazarConfigureRecordAverage:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

function [memorySizeInSamples, bitsPerSample] = ...
         AlazarGetChannelInfo(boardHandle)
    pMemorySizeInSamples = libpointer('uint32Ptr', 0);
    pBitsPerSample = libpointer('uint8Ptr', 0);
    retCode = calllib('ATSApi', ...
                      'AlazarGetChannelInfo', ...
                      boardHandle, ...
                      pMemorySizeInSamples, ...
                      pBitsPerSample);
    if retCode ~= 512
        throw(MException('AlazarGetChannelInfo:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
    memorySizeInSamples = pMemorySizeInSamples.Value;
    bitsPerSample = pBitsPerSample.Value;
end

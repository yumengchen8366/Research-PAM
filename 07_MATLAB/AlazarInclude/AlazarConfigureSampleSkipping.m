function AlazarConfigureSampleSkipping(boardHandle, ...
                                       mode, ...
                                       sampleClocksPerRecord, ...
                                       pSampleSkippingBitmap)
    retCode = calllib('ATSApi', ...
                      'AlazarConfigureSampleSkipping', ...
                      boardHandle, ...
                      mode, ...
                      sampleClocksPerRecord, ...
                      pSampleSkippingBitmap);
    if retCode ~= 512
        throw(MException('AlazarConfigureSampleSkipping:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

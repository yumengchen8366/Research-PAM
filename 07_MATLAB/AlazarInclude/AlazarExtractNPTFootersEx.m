function footers = AlazarExtractNPTFootersEx(buffer, ...
                                             options, ...
                                             recordSize_bytes, ...
                                             bufferSize_bytes, ...
                                             numFootersToExtract)
    for n = 1:numFootersToExtract
        footers(n).triggerTimestamp = 0;
        footers(n).recordNumber = 0;
        footers(n).frameCount = 0;
        footers(n).aux_in_state = 0;
    end
    pFooters = libpointer('NPTFooter', footers);
    retCode = calllib('ATSApi', ...
                      'AlazarExtractNPTFootersEx', ...
                      buffer, ...
                      options, ...
                      recordSize_bytes, ...
                      bufferSize_bytes, ...
                      pFooters, ...
                      numFootersToExtract);
    if retCode ~= 512
        throw(MException('AlazarExtractNPTFootersEx:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
    footers = pFooters.value;
end

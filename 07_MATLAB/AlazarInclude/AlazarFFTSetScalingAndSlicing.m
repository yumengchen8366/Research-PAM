function AlazarFFTSetScalingAndSlicing(dspHandle, ...
                                       slice_pos, ...
                                       loge_ampl_mult)
    retCode = calllib('ATSApi', ...
                      'AlazarFFTSetScalingAndSlicing', ...
                      dspHandle, ...
                      slice_pos, ...
                      loge_ampl_mult);
    if retCode ~= 512
        throw(MException('AlazarFFTSetScalingAndSlicing:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

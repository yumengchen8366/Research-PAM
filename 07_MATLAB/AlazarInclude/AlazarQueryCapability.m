function value = AlazarQueryCapability(boardHandle, capability)
    pValue = libpointer('uint32Ptr', 0);
    retCode = calllib('ATSApi', ...
                      'AlazarQueryCapability', ...
                      boardHandle, ...
                      capability, ...
                      0, ...
                      pValue);
    if retCode ~= 512
        throw(MException('AlazarQueryCapability:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
    value = pValue.Value;
end

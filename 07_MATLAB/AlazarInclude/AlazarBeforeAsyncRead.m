function AlazarBeforeAsyncRead(boardHandle, ...
                               channelSelect, ...
                               transferOffset, ...
                               samplesPerRecord, ...
                               recordsPerBuffer, ...
                               recordsPerAcquisition, ...
                               flags)
    retCode = calllib('ATSApi', ...
                      'AlazarBeforeAsyncRead', ...
                      boardHandle, ...
                      channelSelect, ...
                      transferOffset, ...
                      samplesPerRecord, ...
                      recordsPerBuffer, ...
                      recordsPerAcquisition, ...
                      flags);
    if retCode ~= 512
        throw(MException('AlazarBeforeAsyncRead:error', '%s', errorToText(retCode)));
    end
end

function AlazarInputControl(boardHandle, ...
                            channelId, ...
                            couplingId, ...
                            rangeId, ...
                            impedanceId)
    retCode = calllib('ATSApi', ...
                      'AlazarInputControl', ...
                      boardHandle, ...
                      channelId, ...
                      couplingId, ...
                      rangeId, ...
                      impedanceId);
    if retCode ~= 512
        throw(MException('AlazarInputControl:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

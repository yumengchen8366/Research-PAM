function [dspModuleId, ...
          versionMajor, ...
          versionMinor, ...
          maxLength, ...
          reserved0, ...
          reserved1] = AlazarDSPGetInfo(dspHandle)
    pDspModuleId = libpointer('uint32Ptr', 0);
    pVersionMajor = libpointer('uint16Ptr', 0);
    pVersionMinor = libpointer('uint16Ptr', 0);
    pMaxLength = libpointer('uint32Ptr', 0);
    pReserved0 = libpointer('uint32Ptr', 0);
    pReserved1 = libpointer('uint32Ptr', 0);
    retCode = calllib('ATSApi', ...
                      'AlazarDSPGetInfo', ...
                      dspHandle, ...
                      pDspModuleId, ...
                      pVersionMajor, ...
                      pVersionMinor, ...
                      pMaxLength, ...
                      pReserved0, ...
                      pReserved1);
    if retCode ~= 512
        throw(MException('AlazarDSPGetInfo:error', '%s', errorToText(retCode)));
    end
    dspModuleId = pDspModuleId.Value;
    versionMajor = pVersionMajor.Value;
    versionMinor = pVersionMinor.Value;
    maxLength = pMaxLength.Value;
    reserved0 = pReserved0.Value;
    reserved1 = pReserved1.Value;
end

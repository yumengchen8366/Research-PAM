function [backgroundRecord] = ...
         AlazarFFTBackgroundSubtractionGetRecordS16(dspHandle, size_samples)
    pBackgroundRecord = libpointer('int16Ptr', zeros(1, size_samples));
    retCode = calllib('ATSApi', ...
                      'AlazarFFTBackgroundSubtractionGetRecordS16', ...
                      dspHandle, ...
                      pBackgroundRecord, ...
                      size_samples);
    if retCode ~= 512
        throw(MException('AlazarFFTBackgroundSubtractionGetRecordS16:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
    backgroundRecord = pBackgroundRecord.Value;
end

function AlazarPostAsyncBuffer(boardHandle, pBuffer, bufferLength)
    retCode = calllib('ATSApi', ...
                      'AlazarPostAsyncBuffer', ...
                      boardHandle, ...
                      pBuffer, ...
                      bufferLength);
    if retCode ~= 512
        throw(MException('AlazarPostAsyncBuffer:error', ...
                         '%s', errorToText(retCode)));
    end
end

function result = AlazarDSPGetParameterU32(dspHandle, parameter)
    pResult = libpointer('uint32Ptr', 0);
    retCode = calllib('ATSApi', ...
                      'AlazarDSPGetParameterU32', ...
                      dspHandle, ...
                      parameter, ...
                      pResult);
    if retCode ~= 512
        throw(MException('AlazarDSPGetParameterU32:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
    result = pResult.value;
end

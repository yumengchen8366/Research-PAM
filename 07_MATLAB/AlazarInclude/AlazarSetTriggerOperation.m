function AlazarSetTriggerOperation(boardHandle, ...
                                   triggerOperation, ...
                                   triggerEngineId1, ...
                                   sourceId1, ...
                                   slopeId1, ...
                                   level1, ...
                                   triggerEngineId2, ...
                                   sourceId2, ...
                                   slopeId2, ...
                                   level2)
    retCode = calllib('ATSApi', ...
                      'AlazarSetTriggerOperation', ...
                      boardHandle, ...
                      triggerOperation, ...
                      triggerEngineId1, ...
                      sourceId1, ...
                      slopeId1, ...
                      level1, ...
                      triggerEngineId2, ...
                      sourceId2, ...
                      slopeId2, ...
                      level2);
    if retCode ~= 512
        throw(MException('AlazarSetTriggerOperation:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

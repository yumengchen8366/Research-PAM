function [majorNumber, minorNumber] = AlazarGetFPGAVersion(boardHandle)
    pMajorNumber = libpointer('uint8Ptr', 0);
    pMinorNumber = libpointer('uint8Ptr', 0);
    retCode = calllib('ATSApi', ...
                      'AlazarGetFPGAVersion', ...
                      boardHandle, ...
                      pMajorNumber, ...
                      pMinorNumber);
    if retCode ~= 512
        throw(MException('AlazarGetFPGAVersion:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
    majorNumber = pMajorNumber.Value;
    minorNumber = pMinorNumber.Value;
end

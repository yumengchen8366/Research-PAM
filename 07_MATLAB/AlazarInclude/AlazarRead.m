function AlazarRead(boardHandle, ...
                    channelId, ...
                    pBuffer, ...
                    elementSize, ...
                    record, ...
                    transferOffset, ...
                    transferLength)
    retCode = calllib('ATSApi', ...
                      'AlazarRead', ...
                      boardHandle, ...
                      channelId, ...
                      pBuffer, ...
                      elementSize, ...
                      record, ...
                      transferOffset, ...
                      transferLength);
    if retCode ~= 512
        throw(MException('AlazarRead:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

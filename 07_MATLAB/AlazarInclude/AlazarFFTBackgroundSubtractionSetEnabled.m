function AlazarFFTBackgroundSubtractionSetEnabled(dspHandle, enabled)
    retCode = calllib('ATSApi', ...
                      'AlazarFFTBackgroundSubtractionSetEnabled', ...
                      dspHandle, ...
                      enabled);
    if retCode ~= 512
        throw(MException('AlazarFFTBackgroundSubtractionSetEnabled:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

function AlazarSetTriggerOperationForScanning(boardHandle, ...
                                              triggerSlopeId, ...
                                              triggerLevel, ...
                                              options)
    retCode = calllib('ATSApi', ...
                      'AlazarSetTriggerOperationForScanning', ...
                      boardHandle, ...
                      triggerSlopeId, ...
                      triggerLevel, ...
                      options);
    if retCode ~= 512
        throw(MException('AlazarSetTriggerOperationForScanning:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end

function [majorVersion, minorVersion] = ...
         AlazarGetBoardRevision(boardHandle)
    pMajorVersion = libpointer('uint8Ptr', 0);
    pMinorVersion = libpointer('uint8Ptr', 0);
    retCode = calllib('ATSApi', ...
                      'AlazarGetBoardRevision', ...
                      boardHandle, ...
                      pMajorVersion, ...
                      pMinorVersion);
    if retCode ~= 512
        throw(MException('AlazarGetBoardRevision:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
    majorVersion = pMajorVersion.Value;
    minorVersion = pMinorVersion.Value;
end

function AlazarResetTimeStamp(boardHandle, option)
    retCode = calllib('ATSApi', ...
                      'AlazarResetTimeStamp', ...
                      boardHandle, ...
                      option);
    if retCode ~= 512
        throw(MException('AlazarResetTimeStamp:error', ...
                         '%s', ...
                         errorToText(retCode)));
    end
end
